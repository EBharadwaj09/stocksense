"""Command line: ``python -m stocksense_ml {backtest,forecast,synth}``.

``make train`` runs ``backtest`` on the default datasets and writes ``reports/metrics.md``
and ``reports/metrics.json``.
"""

from __future__ import annotations

import argparse
import json
import platform
import tempfile
import time
from importlib import metadata
from pathlib import Path

import pandas as pd

from .backtest import BacktestResult, forecast, run_backtest
from .data import Panel, load_panel
from .demo import main as demo_main
from .nightly import main as nightly_main
from .synth import generate

REPO_ROOT = Path(__file__).resolve().parents[2]
SAMPLE = REPO_ROOT / "samples" / "sample-sales-1-year.csv"


def _version(pkg: str) -> str:
    try:
        return metadata.version(pkg)
    except metadata.PackageNotFoundError:
        return "not installed"


def _load(spec: str, max_series: int | None) -> tuple[str, Panel]:
    """``synthetic`` or a CSV path."""
    if spec == "synthetic":
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "synthetic.csv"
            generate().to_csv(path, index=False)
            return "Synthetic shop, ~3 years (generated, seed 7)", load_panel(path)
    path = Path(spec)
    label = "Sample shop, 1 year (samples/)" if path.resolve() == SAMPLE else path.name
    return label, load_panel(path, max_series=max_series)


def _fmt_table(metrics: pd.DataFrame, best: str) -> str:
    lines = ["| Model | MAE (units/day) | WAPE | Bias | WAPE festive days |", "|---|---:|---:|---:|---:|"]
    for model, r in metrics.iterrows():
        name = f"**{model}**" if model == best else model
        lines.append(
            f"| {name} | {r['MAE']:.2f} | {r['WAPE']:.1%} | {r['Bias']:+.1%} | {r['WAPE festive days']:.1%} |"
        )
    return "\n".join(lines)


def _section(label: str, panel: Panel, res: BacktestResult, seconds: float) -> tuple[str, dict]:
    metrics = res.metrics()
    best = metrics["WAPE"].idxmin()
    gbm = res.models[-1]
    best_baseline = metrics.drop(index=gbm)["WAPE"].min()
    gain = 1 - metrics.loc[gbm, "WAPE"] / best_baseline
    n = len(res.predictions)
    text = [
        f"### {label}",
        "",
        f"{panel.n_products} products · {panel.n_days} days "
        f"({panel.dates[0]:%Y-%m-%d} to {panel.dates[-1]:%Y-%m-%d}) · {panel.skipped_rows} invalid rows skipped  ",
        f"{len(res.origins)} weekly origins ({res.origins[0]:%Y-%m-%d} to {res.origins[-1]:%Y-%m-%d}) · "
        f"{res.horizon}-day horizon · {n:,} scored forecasts · {seconds:.0f} s",
        "",
        _fmt_table(metrics, best),
        "",
        f"{gbm} WAPE is **{gain:.1%} lower** than the best baseline." if gain >= 0
        else f"{gbm} WAPE is **{-gain:.1%} higher** than the best baseline.",
    ]
    if res.feature_importance is not None:
        top = ", ".join(f"{k} {v:.0%}" for k, v in res.feature_importance.head(6).items())
        text += ["", f"Top features (gain): {top}."]
    by_h = res.predictions.groupby("h")
    wape_h = (by_h.apply(lambda g: (g[gbm] - g["y"]).abs().sum() / g["y"].sum(), include_groups=False)).round(3)
    data = {
        "dataset": label,
        "products": panel.n_products,
        "days": panel.n_days,
        "first_day": f"{panel.dates[0]:%Y-%m-%d}",
        "last_day": f"{panel.dates[-1]:%Y-%m-%d}",
        "origins": [f"{o:%Y-%m-%d}" for o in res.origins],
        "horizon": res.horizon,
        "scored_forecasts": n,
        "metrics": json.loads(metrics.round(4).to_json(orient="index")),
        "gbm_wape_by_horizon": {int(k): float(v) for k, v in wape_h.items()},
        "gbm_relative_improvement": round(float(gain), 4),
    }
    return "\n".join(text), data


def cmd_backtest(args: argparse.Namespace) -> int:
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    specs = args.data or [str(SAMPLE), "synthetic"]
    sections, datasets, engine = [], [], None
    for spec in specs:
        label, panel = _load(spec, args.max_series)
        started = time.perf_counter()
        res = run_backtest(panel, n_origins=args.origins, step=7, horizon=args.horizon, engine=args.engine)
        engine = res.engine
        text, data = _section(label, panel, res, time.perf_counter() - started)
        sections.append(text)
        datasets.append(data)
        print(text, "\n", flush=True)

    env = (
        f"Python {platform.python_version()} · pandas {_version('pandas')} · numpy {_version('numpy')} · "
        + (f"LightGBM {_version('lightgbm')}" if engine == "lightgbm" else f"scikit-learn {_version('scikit-learn')}")
    )
    report = "\n".join(
        [
            "# StockSense forecast backtest",
            "",
            "Generated by `make train`. Do not edit by hand.",
            "",
            "- **MAE**: average absolute error per product-day, in units.",
            "- **WAPE**: total absolute error / total units sold (lower is better; 20% = off by 1 in 5 units).",
            "- **Bias**: total forecast / total actual - 1 (positive = over-forecasting).",
            "- **WAPE festive days**: WAPE on target days inside a festival shopping window.",
            "- Rolling origin: at each weekly origin the model is retrained on data up to that day only "
            "and forecasts the next 14 days for every product.",
            "",
            *[s + "\n" for s in sections],
            "Both datasets are synthetic. These numbers show the pipeline works and beats simple rules on "
            "data with known patterns; accuracy on a real shop is only known once real sales history exists.",
            "",
            f"Environment: {env}.",
            "",
        ]
    )
    (out / "metrics.md").write_text(report)
    (out / "metrics.json").write_text(json.dumps({"engine": engine, "datasets": datasets}, indent=2) + "\n")
    print(f"Wrote {out / 'metrics.md'} and {out / 'metrics.json'}")
    return 0


def cmd_forecast(args: argparse.Namespace) -> int:
    _, panel = _load(args.data, args.max_series)
    fc = forecast(panel, horizon=args.horizon, engine=args.engine)
    fc.to_csv(args.out, index=False)
    print(f"Wrote {len(fc)} rows to {args.out}")
    return 0


def cmd_synth(args: argparse.Namespace) -> int:
    generate(start=args.start, end=args.end, seed=args.seed).to_csv(args.out, index=False)
    print(f"Wrote {args.out}")
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="stocksense_ml")
    sub = p.add_subparsers(dest="cmd", required=True)

    b = sub.add_parser("backtest", help="rolling-origin backtest, writes the metrics report")
    b.add_argument("--data", action="append", help="CSV path or 'synthetic' (repeatable; default: sample + synthetic)")
    b.add_argument("--out", default="reports")
    b.add_argument("--origins", type=int, default=8)
    b.add_argument("--horizon", type=int, default=14)
    b.add_argument("--engine", default="auto", choices=["auto", "lightgbm", "sklearn"])
    b.add_argument("--max-series", type=int, default=None, help="limit series (large Kaggle files)")
    b.set_defaults(func=cmd_backtest)

    f = sub.add_parser("forecast", help="train on all history, forecast the next days")
    f.add_argument("--data", default=str(SAMPLE))
    f.add_argument("--out", default="forecast.csv")
    f.add_argument("--horizon", type=int, default=14)
    f.add_argument("--engine", default="auto", choices=["auto", "lightgbm", "sklearn"])
    f.add_argument("--max-series", type=int, default=None)
    f.set_defaults(func=cmd_forecast)

    n = sub.add_parser("nightly", help="forecast every shop in Supabase and store the results")
    n.add_argument("--dry-run", action="store_true", help="read and forecast, but write nothing")
    n.add_argument("--engine", default="auto", choices=["auto", "lightgbm", "sklearn"])
    n.set_defaults(func=lambda a: nightly_main(dry_run=a.dry_run, engine=a.engine))

    d = sub.add_parser("demo-reset", help="reset the public demo account and reload its sample shop")
    d.add_argument("--dry-run", action="store_true", help="plan the reset, but call nothing")
    d.set_defaults(func=lambda a: demo_main(dry_run=a.dry_run))

    s = sub.add_parser("synth", help="write the synthetic dataset as CSV")
    s.add_argument("--out", default="synthetic-sales.csv")
    s.add_argument("--start", default="2024-01-01")
    s.add_argument("--end", default="2026-10-25")
    s.add_argument("--seed", type=int, default=7)
    s.set_defaults(func=cmd_synth)

    args = p.parse_args(argv)
    return args.func(args)
